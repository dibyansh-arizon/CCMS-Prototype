import assert from 'node:assert/strict';
import * as E from '../src/engine.js';
import { makeCtx } from '../src/ctx.js';
import { buildSeed } from '../src/seed.js';
import { userById, USERS } from '../src/data/people.js';
import { ASSESSMENTS } from '../src/data/forms.js';

let pass = 0;
const t = (name, fn) => { try { fn(); pass++; console.log('  ok  ', name); } catch (e) { console.error('  FAIL', name, '\n       ', e.message); process.exitCode = 1; } };
const throwsWF = (fn, re) => assert.throws(fn, (e) => e instanceof E.WorkflowError && (!re || re.test(e.message)));

const seed = buildSeed(new Date());
const st = { counters: seed.counters, delegations: seed.delegations, settings: seed.settings };
const ctx = (uid, extra = {}) => makeCtx(userById(uid), { ...st, now: new Date(), ...extra });
const rec = (pred) => seed.records.find(pred);

console.log('Seed data');
t('11 demo records generated by the engine', () => assert.equal(seed.records.length, 11));
t('every record has an activity history', () => seed.records.forEach((r) => assert.ok(r.history.length >= 1)));
t('CC numbers are unique and sequential CCYYNNN', () => {
  const nums = seed.records.map((r) => r.ccNumber).filter(Boolean);
  assert.equal(new Set(nums).size, nums.length);
  nums.forEach((n) => assert.match(n, /^CC\d{2}\d{3}$/));
});
t('closed record is final and has an archive reference', () => { const r = rec((x) => x.status === 'Closed'); assert.ok(r.archiveRef); assert.ok(E.isFinal(r)); });

console.log('Exact QAD questions & department visibility');
t('7 assessments with exact question wording', () => {
  assert.equal(ASSESSMENTS.length, 7);
  assert.equal(ASSESSMENTS.find((a) => a.key === 'qad').fields.length, 3);
  assert.equal(ASSESSMENTS.find((a) => a.key === 'qad').fields[0].label, 'Is there an impact on the Stability Protocol?');
});
t('QA Head can only open the QAD assessment in Stage 3', () => {
  const r = rec((x) => x.status === 'Departmental Assessment');
  assert.deepEqual(E.perms(r, ctx('u_neha')).assessKeys, ['qad']);
});
t('Operations head can only open Validation/Qualification', () => {
  const r = rec((x) => x.status === 'Departmental Assessment');
  assert.deepEqual(E.perms(r, ctx('u_rajesh')).assessKeys, []);  // already accepted in seed
  const r2 = rec((x) => x.status === 'Departmental Assessment');
  const a = r2.assessments.find((x) => x.key === 'validation');
  assert.equal(a.status, 'Accepted with Action');
});
t('Training assessment goes to the initiating department head', () => {
  const r = rec((x) => x.status === 'Departmental Assessment');
  assert.deepEqual(r.assessments.find((a) => a.key === 'training').assignees, ['u_vikram']);
  const qc = rec((x) => x.ccNumber && x.department === 'Quality Control');
  assert.deepEqual(qc.assessments.find((a) => a.key === 'training').assignees, ['u_meenal']);
});
t('ARD or QCS head can complete analytical/stability', () => {
  const r = rec((x) => x.status === 'Departmental Assessment');
  assert.deepEqual(r.assessments.find((a) => a.key === 'stability').assignees.sort(), ['u_meenal', 'u_saurabh']);
});
t('other departments cannot see assessment content while assessments run', () => {
  const r = rec((x) => x.status === 'Departmental Assessment');
  const stab = r.assessments.find((a) => a.key === 'stability');
  assert.equal(E.canViewAssessment(r, stab, ctx('u_ananya')), false);
  assert.equal(E.canViewAssessment(r, stab, ctx('u_saurabh')), true);
  assert.equal(E.canViewAssessment(r, stab, ctx('u_neha')), false);
});

console.log('Stages 1–2');
let r = E.createDraft(ctx('u_ananya'), { title: 'Test change', type: 'SOP', description: 'd', currentState: 'c', proposedChange: 'p', justification: 'j' });
t('draft has temporary ID and no CC number', () => { assert.match(r.draftId, /^DRAFT-/); assert.equal(r.ccNumber, null); });
t('submit requires mandatory fields', () => { const bad = E.createDraft(ctx('u_ananya'), { title: 'x' }); throwsWF(() => E.submit(bad, ctx('u_ananya')), /Type of Change/); });
r = E.submit(r, ctx('u_ananya'));
t('only the initiating dept head may endorse', () => { throwsWF(() => E.endorse(r, ctx('u_meenal'), { decision: 'endorse' })); throwsWF(() => E.endorse(r, ctx('u_ananya'), { decision: 'endorse' })); });
t('return requires a comment', () => throwsWF(() => E.endorse(r, ctx('u_vikram'), { decision: 'return' }), /comment/));
t('delegate (Arjun) can endorse for Vikram', () => { const x = E.endorse(r, ctx('u_arjun'), { decision: 'endorse' }); assert.equal(x.status, 'Pending QA Screening'); });
r = E.endorse(r, ctx('u_vikram'), { decision: 'endorse', comment: 'ok' });
t('QA screening cannot accept without checks', () => throwsWF(() => E.screen(r, ctx('u_priya'), { decision: 'accept', checks: {} }), /Confirm/));
t('endorsement does not authorize implementation', () => assert.equal(E.perms(r, ctx('u_karan')).manageActions, false));
r = E.screen(r, ctx('u_priya'), { decision: 'accept', checks: { complete: true, justified: true, noDuplicate: true } });
t('CC number issued at QA acceptance; 7 assessments sent in parallel', () => { assert.match(r.ccNumber, /^CC\d{5}$/); assert.equal(r.assessments.length, 7); assert.ok(r.assessments.every((a) => a.status === 'Pending')); });

console.log('Stage 3 rules');
t('accept with action needs an action', () => throwsWF(() => E.assess(r, ctx('u_rajesh'), 'validation', { decision: 'accept_action', answers: { process: 'No', cleaning: 'No', equipment: 'No' } }), /at least one action/));
t('not acceptable needs justification', () => throwsWF(() => E.assess(r, ctx('u_rajesh'), 'validation', { decision: 'reject', answers: { process: 'No', cleaning: 'No', equipment: 'No' } }), /Justification/));
t('all questions must be answered', () => throwsWF(() => E.assess(r, ctx('u_rajesh'), 'validation', { decision: 'accept', answers: { process: 'No' } }), /Cleaning/));
t('wrong department cannot answer', () => throwsWF(() => E.assess(r, ctx('u_neha'), 'validation', { decision: 'accept', answers: {} }), /not assigned/));
r = E.assess(r, ctx('u_saurabh'), 'analytical', { decision: 'clarify', clarificationText: 'Which equipment?' });
t('clarification pauses only that assessment', () => { assert.equal(r.assessments.find((a) => a.key === 'analytical').status, 'Clarification Requested'); assert.equal(r.status, 'Departmental Assessment'); });
r = E.assess(r, ctx('u_rajesh'), 'validation', { decision: 'accept_action', answers: { process: 'No', cleaning: 'No', equipment: 'Yes' }, actions: [{ description: 'IQ/OQ', ownerId: 'u_nikhil', due: '2027-01-30' }] });
t('other assessments continue independently', () => assert.equal(r.assessments.find((a) => a.key === 'validation').status, 'Accepted with Action'));
r = E.respondClarification(r, ctx('u_ananya'), 'analytical', 'HPLC-04');
const A = { stability: { required: 'No' }, computer: { validation: 'No' }, safety: { operator: 'No', environment: 'No' }, training: { departments: ['OPS'], trainingType: 'Read and Understand' }, qad: { stabilityProtocol: 'No', vendor: 'No', qualityAgreement: 'No' } };
r = E.assess(r, ctx('u_meenal'), 'analytical', { decision: 'accept', answers: { method: 'No', equipment: 'No' } });
r = E.assess(r, ctx('u_meenal'), 'stability', { decision: 'accept', answers: A.stability });
r = E.assess(r, ctx('u_vivek'), 'computer', { decision: 'accept', answers: A.computer });
r = E.assess(r, ctx('u_kavita'), 'safety', { decision: 'reject', answers: A.safety, justification: 'Unsafe fumes' });
t('Not Acceptable blocks progress until QA resolves', () => { assert.equal(r.status, 'Departmental Assessment'); assert.deepEqual(E.perms(r, ctx('u_priya')).resolveKeys, ['safety']); });
r = E.resolveNotAcceptable(r, ctx('u_priya'), 'safety', { outcome: 'reassess', note: 'Re-evaluate with mitigation' });
r = E.assess(r, ctx('u_kavita'), 'safety', { decision: 'accept', answers: A.safety });
r = E.assess(r, ctx('u_vikram'), 'training', { decision: 'accept', answers: A.training });
t('workflow waits for QAD assessment', () => assert.equal(r.status, 'Departmental Assessment'));
r = E.assess(r, ctx('u_neha'), 'qad', { decision: 'accept', answers: A.qad });
t('moves to Regulatory when all assessments complete', () => assert.equal(r.status, 'Regulatory Assessment'));

console.log('Stages 4–6');
t('client approval needs name and owner', () => throwsWF(() => E.regulatory(r, ctx('u_meera'), { andaStatus: 'Not Applicable', applicable: 'Not Applicable', regActionRequired: false, clientRequired: true }), /client name/));
r = E.regulatory(r, ctx('u_meera'), { andaStatus: 'Not Applicable', applicable: 'Not Applicable', regActionRequired: false, clientRequired: true, clientName: 'Acme Pharma', clientOwnerId: 'u_sonal' });
t('client approval action created for the assigned employee', () => { const a = r.actions.find((x) => x.kind === 'client'); assert.equal(a.ownerId, 'u_sonal'); assert.equal(a.status, 'Planned'); });
t('consolidation is initiator only', () => { throwsWF(() => E.consolidate(r, ctx('u_priya'), { decision: 'submit' })); });
r = E.consolidate(r, ctx('u_ananya'), { decision: 'submit' });
t('QA approval blocked by client gate until evidence is uploaded', () => throwsWF(() => E.qaApprove(r, ctx('u_neha'), { decision: 'approve', answers: { q1a: 'No', q1b: 'No', q1c: 'No', q1d: 'No', q2a: 'No' }, dueDate: '2027-03-01' }), /Client approval/));
t('only the assigned employee uploads evidence', () => throwsWF(() => E.uploadClientEvidence(r, ctx('u_karan'), { fileName: 'x.pdf', reviewedBy: 'A' })));
r = E.uploadClientEvidence(r, ctx('u_sonal'), { fileName: 'approval.pdf', reviewedBy: 'Dr X' });
t('initiator cannot approve own change; QA head can', () => { throwsWF(() => E.qaApprove(r, ctx('u_ananya'), { decision: 'approve' })); });
t('due date cannot be earlier than the latest action due date', () => throwsWF(() => E.qaApprove(r, ctx('u_neha'), { decision: 'approve', answers: { q1a: 'No', q1b: 'No', q1c: 'No', q1d: 'No', q2a: 'No' }, dueDate: '2026-12-01' }), /earlier than the latest action/));
t('actions are locked before approval', () => throwsWF(() => E.updateAction(r, ctx('u_nikhil'), 'ACT-01', { status: 'In Progress' })));
r = E.qaApprove(r, ctx('u_neha'), { decision: 'approve', answers: { q1a: 'No', q1b: 'No', q1c: 'No', q1d: 'No', q2a: 'No' }, dueDate: '2027-03-01', comments: 'ok' });
t('approval authorizes implementation and releases actions', () => { assert.equal(r.status, 'Implementation in Progress'); assert.ok(r.actions.every((a) => ['Not Started', 'Completed'].includes(a.status))); });

console.log('Stages 7–8');
t('completion needs a comment', () => throwsWF(() => E.updateAction(r, ctx('u_nikhil'), 'ACT-01', { status: 'Completed' }), /comment/));
t('only the owner updates an action', () => throwsWF(() => E.updateAction(r, ctx('u_karan'), 'ACT-01', { status: 'In Progress' })));
t('verification blocked while actions open', () => throwsWF(() => E.verify(r, ctx('u_ananya'), {}), /completed/));
r = E.updateAction(r, ctx('u_nikhil'), 'ACT-01', { status: 'Completed', comment: 'Done', evidenceName: 'iqoq.pdf' });
t('amendment: initiator requests, QA authorizes, new action appears', () => {
  let x = E.requestAmendment(r, ctx('u_ananya'), { description: 'Extra check', reason: 'Missed', ownerId: 'u_karan', due: '2027-02-01' });
  assert.equal(E.perms(x, ctx('u_ananya')).verify, false);
  x = E.decideAmendment(x, ctx('u_priya'), 'AMD-1', { decision: 'authorize' });
  assert.equal(x.actions.length, r.actions.length + 1);
});
t('SOP change needs the QAD-approved SOP number', () => throwsWF(() => E.verify(r, ctx('u_ananya'), {}), /SOP/));
r = E.verify(r, ctx('u_ananya'), { sopNumber: 'SOP-1 v2' });
t('closeout needs all 8 questions', () => throwsWF(() => E.closeout(r, ctx('u_priya'), { decision: 'close', answers: { c1: 'Yes' } }), /closeout question/));
t('only Head of QAD can cancel', () => throwsWF(() => E.closeout(r, ctx('u_priya'), { decision: 'cancel', cancelReason: 'x' }), /Head of QAD/));
r = E.closeout(r, ctx('u_priya'), { decision: 'close', answers: { c1: 'Yes', c2: 'Yes', c3: 'Yes', c4: 'No', c5: 'No', c6: 'Yes', c7: 'No', c8: 'Yes' } });
t('closed record is read-only, archived and fully logged', () => { assert.equal(r.status, 'Closed'); assert.ok(r.history.length > 20); assert.ok(r.history.some((h) => h.signature)); });

console.log('Extension chain');
const impl = rec((x) => x.status === 'Implementation in Progress');
t('extension levels follow SOP 5.11 chain', () => {
  let x = E.requestExtension(impl, ctx('u_ananya'), { reason: 'Vendor delay' });
  assert.equal(x.extensions[0].chain.length, 1);
  const before = x.dueDate;
  x = E.decideExtension(x, ctx('u_priya'), 'EXT-1', { decision: 'approve' });
  assert.equal(x.extensions[0].status, 'Approved');
  assert.equal(x.dueDate, E.isoDate(E.addDays(before, 60)));
  x = E.requestExtension(x, ctx('u_ananya'), { reason: 'More delay' });
  assert.equal(x.extensions[1].chain.length, 2);
  throwsWF(() => E.decideExtension(x, ctx('u_vikram'), 'EXT-2', { decision: 'approve' }));  // QA reviews first
});
console.log(`\n${pass} checks passed`);
